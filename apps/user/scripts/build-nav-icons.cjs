// Turns the designer's SVGs (assets/updated_icons/*.svg) into react-native-svg components
// (src/components/NavIcons.tsx), so they can change colour with the theme and the active tab.
//
//   node apps/user/scripts/build-nav-icons.cjs        (from the repo root)
//
// Colours in the artwork are mapped to roles: the navy → `ink` (navy in light mode, a light
// blue in dark mode, muted grey when the tab is idle); the sky blue → `accent` (kept when
// active, muted when idle); white stays white. Anything else is kept as drawn.
const fs = require('fs');
const path = require('path');

const DIR = path.join(__dirname, '..', 'assets', 'updated_icons');
const OUT = path.join(__dirname, '..', 'src', 'components', 'NavIcons.tsx');
const ICONS = ['Home', 'Bids', 'Activities', 'Account'];

const COLORS = { 'rgb(22,43,99)': '{c.ink}', 'rgb(76,161,209)': '{c.accent}', white: '"#ffffff"', none: '"none"' };
const color = (v) => COLORS[v.replace(/\s+/g, '')] ?? JSON.stringify(v);
const camel = (k) => k.replace(/-([a-z])/g, (_, ch) => ch.toUpperCase());

/** "fill:rgb(1,2,3);stroke-width:4" → JSX props. */
const styleProps = (style) =>
  style
    .split(';')
    .map((x) => x.trim())
    .filter(Boolean)
    .map((decl) => {
      const [k, ...rest] = decl.split(':');
      const v = rest.join(':').trim();
      if (k === 'clip-rule') return '';
      const name = camel(k.trim());
      return name === 'fill' || name === 'stroke' ? `${name}=${color(v)}` : `${name}={${isNaN(Number(v)) ? JSON.stringify(v) : v}}`;
    })
    .filter(Boolean)
    .join(' ');

const attrs = (raw) => {
  const out = {};
  for (const m of raw.matchAll(/([a-zA-Z:-]+)="([^"]*)"/g)) out[m[1]] = m[2];
  return out;
};

const convert = (file) => {
  const src = fs.readFileSync(path.join(DIR, `${file}.svg`), 'utf8');
  const root = attrs(src.match(/<svg\b([^>]*)>/)[1]);
  const viewBox = root.viewBox;
  const inherited = root.style ? styleProps(root.style) : '';
  const body = src.slice(src.indexOf('>', src.indexOf('<svg')) + 1, src.lastIndexOf('</svg>'));
  const lines = [];
  let depth = 2;
  for (const m of body.matchAll(/<(\/?)([a-zA-Z]+)([^>]*?)(\/?)>/g)) {
    const [, closing, tag, raw, selfClose] = m;
    const pad = '  '.repeat(depth + (closing ? -1 : 0));
    const el = { g: 'G', path: 'Path', circle: 'Circle', rect: 'Rect', ellipse: 'Ellipse', line: 'Line', polygon: 'Polygon', polyline: 'Polyline' }[tag];
    if (!el) throw new Error(`${file}.svg: unsupported element <${tag}>`);
    if (closing) {
      depth -= 1;
      lines.push(`${'  '.repeat(depth)}</${el}>`);
      continue;
    }
    const a = attrs(raw);
    const props = [];
    for (const [k, v] of Object.entries(a)) {
      if (k === 'id' || k === 'style') continue;
      props.push(`${camel(k)}="${v}"`);
    }
    if (a.style) props.push(styleProps(a.style));
    lines.push(`${pad}<${el}${props.length ? ' ' + props.join(' ') : ''}${selfClose ? ' />' : '>'}`);
    if (!selfClose) depth += 1;
  }
  return { viewBox, inherited, jsx: lines.join('\n') };
};

const parts = ICONS.map((name) => ({ name, ...convert(name) }));

const out = `// GENERATED by scripts/build-nav-icons.cjs from assets/updated_icons/*.svg — edit the SVGs and rerun it.
import React from 'react';
import Svg, { Circle, ClipPath, Defs, Ellipse, G, Line, Path, Polygon, Polyline, Rect } from 'react-native-svg';
import { Colors, getThemeMode } from '@ongarage/shared';

void [ClipPath, Defs, Ellipse, Line, Polygon, Polyline, Rect, Circle];

export type NavIconProps = { active: boolean; size?: number };

/** The two artwork colours for a state: the dark "ink" and the light "accent". */
const tones = (active: boolean) =>
  active
    ? { ink: getThemeMode() === 'dark' ? '#cfe6ff' : '#162b63', accent: '#4ca1d1' }
    : { ink: Colors.textMuted, accent: Colors.subtleBorder };

${parts
  .map(
    (p) => `export const ${p.name}Icon: React.FC<NavIconProps> = ({ active, size = 26 }) => {
  const c = tones(active);
  return (
    <Svg width={size} height={size} viewBox="${p.viewBox}">
      <G ${p.inherited}>
${p.jsx
  .split('\n')
  .map((l) => '    ' + l)
  .join('\n')}
      </G>
    </Svg>
  );
};
`
  )
  .join('\n')}`;

fs.writeFileSync(OUT, out);
console.log(`wrote ${path.relative(process.cwd(), OUT)} (${ICONS.join(', ')})`);
