/**
 * Builds src/constants/garageDirectory.ts from the Sri Lanka garage list (assets/Map Data/Ongarage_Garages_SriLanka.csv).
 * Run from the repo root: node apps/user/scripts/build-garage-directory.cjs
 * The list is not on OnGarage yet: every entry is marked `registered: false` until the garage signs up and claims it.
 */
const fs = require('fs');
const path = require('path');

const root = path.join(__dirname, '..');
const csvPath = path.join(root, 'assets', 'Map Data', 'Ongarage_Garages_SriLanka.csv');
const outPath = path.join(root, 'src', 'constants', 'garageDirectory.ts');

/** A small CSV reader: quoted fields may hold commas and line breaks; a UTF-8 BOM is dropped. */
const parseCsv = (text) => {
  const rows = [];
  let row = [];
  let field = '';
  let quoted = false;
  for (let i = 0; i < text.length; i++) {
    const ch = text[i];
    if (quoted) {
      if (ch === '"' && text[i + 1] === '"') {
        field += '"';
        i++;
      } else if (ch === '"') quoted = false;
      else field += ch;
    } else if (ch === '"') quoted = true;
    else if (ch === ',') {
      row.push(field);
      field = '';
    } else if (ch === '\n' || ch === '\r') {
      if (ch === '\r' && text[i + 1] === '\n') i++;
      row.push(field);
      if (row.some((c) => c !== '')) rows.push(row);
      row = [];
      field = '';
    } else field += ch;
  }
  row.push(field);
  if (row.some((c) => c !== '')) rows.push(row);
  return rows;
};

const text = fs.readFileSync(csvPath, 'utf8').replace(/^﻿/, '');
const [header, ...body] = parseCsv(text);
const col = (name) => header.indexOf(name);
const C = {
  district: col('District'),
  name: col('Garage/Workshop Name'),
  category: col('Category'),
  address: col('Address / Locality'),
  phone: col('Phone (Tel/WhatsApp)'),
  website: col('Website'),
  lat: col('Latitude'),
  lng: col('Longitude'),
  source: col('Data Source'),
  sourceLink: col('Source Link'),
};

/** The phone column can hold two numbers joined without a separator ("+9411...+9477..."). Split them; keep the first as the main number. */
const phonesOf = (raw) => (raw || '').split(/(?=\+94)/).map((p) => p.trim()).filter(Boolean);
const q = (s) => JSON.stringify(s ?? '');

const entries = body
  .map((r, i) => {
    const phones = phonesOf(r[C.phone]);
    const lat = Number(r[C.lat]);
    const lng = Number(r[C.lng]);
    if (!Number.isFinite(lat) || !Number.isFinite(lng)) return null;
    // Some map entries have no name. They are kept, named by their kind and place, so no garage in the list is lost.
    const unnamed = !r[C.name];
    const place = r[C.address] || r[C.district];
    const name = unnamed ? `${r[C.category]} · ${place}` : r[C.name];
    return { i, r, phones, lat, lng, name, unnamed };
  })
  .filter(Boolean);

const lines = entries.map(({ i, r, phones, lat, lng, name, unnamed }) => {
  const website = r[C.website] ? `, website: ${q(r[C.website])}` : '';
  const address = r[C.address] ? `, address: ${q(r[C.address])}` : '';
  return `  { id: 'dir-${i + 1}', district: ${q(r[C.district])}, name: ${q(name)}, category: ${q(r[C.category])}${address}, phones: [${phones.map(q).join(', ')}], coords: { latitude: ${lat}, longitude: ${lng} }, source: ${q(r[C.source])}${website}${unnamed ? ', unnamed: true' : ''} },`;
});

const out = `// GENERATED by apps/user/scripts/build-garage-directory.cjs from assets/Map Data/Ongarage_Garages_SriLanka.csv. Do not edit by hand.
// These garages are not on OnGarage yet (registered: false). A garage that signs up and claims its entry replaces it.

export type DirectoryGarage = {
  id: string;
  district: string;
  name: string;
  /** Google's category label from the source list. */
  category: string;
  address?: string;
  /** The first is the main number; a second number, when the list had one, follows. Empty when the list had none. */
  phones: string[];
  coords: { latitude: number; longitude: number };
  /** Where the entry came from (OpenStreetMap, Photon, Rainbow Pages). */
  source: string;
  website?: string;
  /** The source had no name: the name here is the kind of place and its locality. */
  unnamed?: boolean;
};

export const GARAGE_DIRECTORY: DirectoryGarage[] = [
${lines.join('\n')}
];
`;

fs.writeFileSync(outPath, out);
console.log(`Wrote ${entries.length} garages to ${path.relative(root, outPath)}`);
